def seed_if_empty(db: Session):
    if db.scalar(select(Medicine.id).limit(1)) is not None:
        return

    rnd = random.Random(42)  # одинаковые «случайные» цены при каждом запуске

    pharmacies = [Pharmacy(name=n, city=c, address=a, phone=p, hours=h, lat=la, lng=lo)
                  for n, c, a, p, h, la, lo in PHARMACIES]
    db.add_all(pharmacies)

    for i, (name, generic, cat, form, purpose, contra, rx, base) in enumerate(MEDICINES):
        m = Medicine(name=name, generic_name=generic, category=cat, form=form,
                     purpose=purpose, contraindications=contra, prescription=rx)
        m.refresh_search()
        db.add(m)
        # Лекарство есть примерно в 70% аптек, цена ±30% от базовой
        for ph in pharmacies:
            if rnd.random() < 0.7:
                db.add(Offer(medicine=m, pharmacy=ph,
                             price_som=round(base * rnd.uniform(0.8, 1.3)),
                             in_stock=rnd.random() > 0.15))
        if i < 3:
            for author, rating, text in DEMO_REVIEWS:
                db.add(Review(medicine=m, author=author, rating=rating, text=text, status=APPROVED))

    db.commit()
